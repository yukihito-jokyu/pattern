"""仕様からリファレンス（cli.md）を作る（STR-04、OPS-05）。"""

from __future__ import annotations

from typing import Any, Dict, List

import helptext
import model
import vocab

HEADER = "<!-- Code generated by tools/clispec gen from cli.json. DO NOT EDIT. -->"


def render(spec: Dict[str, Any]) -> str:
    lines: List[str] = [HEADER, "", f"# {spec['name']} {spec['version']}", "", spec["summary"], ""]
    lines += ["Implementations print each help text below exactly, to stdout, and exit with 0 "
              "(`-h` and `--help`). See `docs/design/rules.md` OPS-05.", ""]
    single = model.is_single(spec)
    if single:
        command = spec["commands"][0]
        lines += ["## Usage", ""] + _block(helptext.command_help(spec, command)) + [""]
        lines += _command_facts(spec, command)
    else:
        lines += ["## Usage", ""] + _block(helptext.command_help(spec, None)) + [""]
        lines += ["## Commands", ""]
        for command in spec["commands"]:
            lines += [f"### {model.program(spec, command)}", ""]
            lines += _block(helptext.command_help(spec, command)) + [""]
            lines += _command_facts(spec, command)
    if spec["types"]:
        lines += ["## Output types", "",
                  "`--json` writes an object with every field in this order, or an array of such objects. "
                  "Text output is a table whose header is the field names in upper case.", ""]
        for type_ in spec["types"]:
            lines += [f"### {type_['name']}", "", "| Field | Type | Nullable |", "|---|---|---|"]
            for field in type_["fields"]:
                ftype = field["type"] + (f" ({', '.join(field['values'])})" if field["values"] else "")
                if field["list"]:
                    ftype = f"list of {ftype}"
                lines.append(f"| `{field['name']}` | {ftype} | {'yes' if field['nullable'] else 'no'} |")
            lines.append("")
    lines += ["## Exit codes", "", "| Code | Meaning |", "|---|---|"]
    used = sorted({c for command in spec["commands"] for c in command["exit_codes"]})
    lines += [f"| {code} | {vocab.EXIT_CODES[code]} |" for code in used if code in vocab.EXIT_CODES]
    lines.append("")
    if spec["env"]:
        lines += ["## Environment variables", "", "| Name | Type | Default | Description |", "|---|---|---|---|"]
        for env in spec["env"]:
            default = "-" if env["default"] is None else f"`{helptext.format_value(env['default'])}`"
            lines.append(f"| `{env['name']}` | {env['type']} | {default} | {env['summary']} |")
        lines.append("")
        lines.append("A value given by an option takes precedence over the environment variable, "
                     "which takes precedence over the default.")
        lines.append("")
    if spec["storage"] == "data":
        pre = model.prefix(spec["name"])
        lines += ["## Data directory", "", "The first of these that applies is used. "
                  "It is created with permission 0700 if it does not exist.", "",
                  f"1. `{pre}_DATA_DIR`, if it is a non-empty absolute path",
                  f"2. Linux and macOS: `$XDG_DATA_HOME/{spec['name']}`, if `XDG_DATA_HOME` is a non-empty absolute "
                  f"path. Windows: `%LOCALAPPDATA%\\{spec['name']}`",
                  f"3. Linux and macOS: `$HOME/.local/share/{spec['name']}`", ""]
    lines += ["## Version", "", f"`{spec['name']} --version` prints `{spec['name']} {spec['version']}` "
              "and exits with 0.", ""]
    return "\n".join(lines)


def _block(text: str) -> List[str]:
    return ["```text"] + text.rstrip("\n").split("\n") + ["```"]


def _command_facts(spec: Dict[str, Any], command: Dict[str, Any]) -> List[str]:
    output = command["output"]
    kind = output["kind"]
    if kind == "object":
        out = f"one `{output['type']}`"
    elif kind == "list":
        out = f"a list of `{output['type']}`"
    elif kind == "raw":
        out = "the result itself (no `--json`)"
    else:
        out = "nothing"
    codes = ", ".join(str(c) for c in command["exit_codes"])
    return [f"- Output: {out}", f"- Exit codes: {codes}", ""]
