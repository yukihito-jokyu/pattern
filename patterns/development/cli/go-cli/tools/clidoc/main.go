// Command clidoc はコマンドツリーから go-cli のコマンド一覧 docs/cli.md を生成する。
//
// -check 指定時は書き込まず、docs/cli.md が最新でなければ終了コード1で終了する。
package main

import (
	"bytes"
	"flag"
	"fmt"
	"io"
	"os"
	"time"

	"example.com/go-cli/internal/app"
)

const (
	output   = "docs/cli.md"
	header   = "<!-- Code generated by tools/clidoc. DO NOT EDIT. -->\n\n"
	filePerm = 0o600
)

func main() {
	var check bool
	flag.BoolVar(&check, "check", false, "Fail when docs/cli.md is out of date instead of writing it")
	flag.Parse()
	want, err := generate()
	if err != nil {
		fmt.Fprintln(os.Stderr, "clidoc:", err)
		os.Exit(1)
	}
	if check {
		got, err := os.ReadFile(output)
		if err != nil || !bytes.Equal(got, want) {
			fmt.Println("STR-07 " + output + ":1 " + output + " is out of date; run make generate")
			os.Exit(1)
		}
		return
	}
	err = os.WriteFile(output, want, filePerm)
	if err != nil {
		fmt.Fprintln(os.Stderr, "clidoc:", err)
		os.Exit(1)
	}
}

// generate はdocs/cli.md の内容を返す。
func generate() ([]byte, error) {
	a, err := app.New(app.Env{Stdout: io.Discard, Stderr: io.Discard, Getenv: getenv, Now: time.Now})
	if err != nil {
		return nil, fmt.Errorf("build the command tree: %w", err)
	}
	var b bytes.Buffer
	b.WriteString(header)
	err = a.WriteReference(&b)
	if err != nil {
		return nil, fmt.Errorf("write the reference: %w", err)
	}
	return b.Bytes(), nil
}

// getenv はファイルに触れない app.New にデータディレクトリを渡す。
func getenv(key string) string {
	if key == "HOME" {
		return "/nonexistent"
	}
	return ""
}
